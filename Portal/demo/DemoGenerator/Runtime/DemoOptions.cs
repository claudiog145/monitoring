namespace DemoGenerator.Runtime;

/// <summary>Configuration section <c>Demo</c>.</summary>
public sealed class DemoOptions
{
    public const string Section = "Demo";

    /// <summary>Kustainer base URL.</summary>
    public string KustoUrl { get; set; } = "http://localhost:8085";

    /// <summary>Folder whose sub-folders are company packs (each with an <c>archetype.json</c>).</summary>
    public string PacksPath { get; set; } = "../packs";

    /// <summary>Default scale for a reset without one: tiny, laptop or showcase.</summary>
    public string Scale { get; set; } = "laptop";

    public int FeederIntervalSeconds { get; set; } = 60;

    /// <summary>Starts the live feeder with the service.</summary>
    public bool FeederEnabled { get; set; } = true;

    /// <summary>Base seed; each company derives its own from this and its key, so a reset is reproducible.</summary>
    public long Seed { get; set; } = 1000;

    /// <summary>Default backfill days for a reset without one.</summary>
    public int Days { get; set; } = 8;

    /// <summary>Concurrent ingestion commands sent to Kusto.</summary>
    public int IngestParallelism { get; set; } = 4;

    /// <summary>Hours of one app generated by one <c>.set-or-append</c> command during a backfill.</summary>
    public int BatchHours { get; set; } = 6;

    /// <summary><c>persist</c> (survives a Kustainer restart, needs <see cref="KustoDataPath"/>) or <c>volatile</c>.</summary>
    public string DatabasePersistence { get; set; } = "persist";

    /// <summary>Root folder inside the Kustainer container for persistent databases.</summary>
    public string KustoDataPath { get; set; } = "/kustodata/dbs";

    public int KustoTimeoutSeconds { get; set; } = 900;
}
